def s(row, t):
    ws.merge_cells(f"A{row}:E{row}")
    ws.cell(row=row, column=1, value=t).font = sf
    return row + 1

def tbl(ws, r, h, d):
    for i, v in enumerate(h, 1):
        c = ws.cell(row=r, column=i, value=v)
        c.font = hf; c.fill = hfill; c.alignment = wr; c.border = bd
    r += 1
    for rd in d:
        for i, v in enumerate(rd, 1):
            c = ws.cell(row=r, column=i, value=v)
            c.font = bf; c.alignment = wr; c.border = bd
        r += 1
    return r + 1

def n(row, t):
    ws.merge_cells(f"A{row}:E{row}")
    ws.cell(row=row, column=1, value=t).font = bf
    ws.cell(row=row, column=1).alignment = wr
    return row + 1

def w(ws, r, title, hd):
    ws.merge_cells(f"A{r}:E{r}")
    ws.cell(row=r, column=1, value=title).font = Font(name="微软雅黑", bold=True, size=12, color="2F5496")
    r += 1
    return tbl(ws, r, hd[0], hd[1])

