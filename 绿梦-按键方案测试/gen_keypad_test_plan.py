def title_row(ws, row, text):
    ws.merge_cells(f"A{row}:F{row}")
    ws.cell(row=row, column=1, value=text).font = title_font
    return row + 1

def section(ws, row, text):
    ws.merge_cells(f"A{row}:F{row}")
    ws.cell(row=row, column=1, value=text).font = Font(name="微软雅黑", bold=True, size=13, color="2F5496")
    return row + 1

def body_row(ws, row, text):
    ws.merge_cells(f"A{row}:F{row}")
    c = ws.cell(row=row, column=1, value=text)
    c.font = body_font; c.alignment = wrap
    return row + 1

def tbl(ws, row, headers, data):
    for i, h in enumerate(headers, 1):
        c = ws.cell(row=row, column=i, value=h)
        c.font = Font(name="微软雅黑", bold=True, size=10, color="FFFFFF")
        c.fill = header_fill; c.alignment = wrap; c.border = border
    row += 1
    for d in data:
        for i, v in enumerate(d, 1):
            c = ws.cell(row=row, column=i, value=v)
            c.font = body_font; c.alignment = wrap; c.border = border
        row += 1
    return row + 1

