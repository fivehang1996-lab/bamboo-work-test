# ============================================================
# 通用样式
# ============================================================
header_font = Font(name="微软雅黑", bold=True, size=11, color="FFFFFF")
header_fill = PatternFill(start_color="2F5496", end_color="2F5496", fill_type="solid")
wrap_align = Alignment(wrap_text=True, vertical="top")
thin_border = Border(
    left=Side(style="thin"), right=Side(style="thin"),
    top=Side(style="thin"), bottom=Side(style="thin")
)
pos_fill = PatternFill(start_color="E2EFDA", end_color="E2EFDA", fill_type="solid")
neg_fill = PatternFill(start_color="FCE4D6", end_color="FCE4D6", fill_type="solid")
neu_fill = PatternFill(start_color="F2F2F2", end_color="F2F2F2", fill_type="solid")
mixed_fill = PatternFill(start_color="FFF2CC", end_color="FFF2CC", fill_type="solid")
red_fill = PatternFill(start_color="FF6B6B", end_color="FF6B6B", fill_type="solid")

def write_coding_sheet(ws, title, data):
    ws.title = title
    headers = ["序号", "发言者", "核心观点", "情感", "话题标签", "原始引文", "潜在主题归并"]
    for col, h in enumerate(headers, 1):
        c = ws.cell(row=1, column=col, value=h)
        c.font = header_font
        c.fill = header_fill
        c.alignment = wrap_align
        c.border = thin_border

    for i, item in enumerate(data, 2):
        seq, speaker, point, sentiment, tags, quote, theme = item
        row_data = [seq, speaker, point, sentiment, tags, quote, theme]
        for col, val in enumerate(row_data, 1):
            c = ws.cell(row=i, column=col, value=val)
            c.alignment = wrap_align
            c.border = thin_border
            c.font = Font(name="微软雅黑", size=10)
            if "+" in sentiment and "-" not in sentiment:
                c.fill = pos_fill
            elif "-" in sentiment and "+" not in sentiment:
                c.fill = neg_fill
            else:
                c.fill = neu_fill if "=" in sentiment else mixed_fill

    for i, w in enumerate([6, 14, 44, 8, 28, 65, 32], 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:G{len(data)+1}"

def write_stats_sheet(ws, title, data):
    ws.title = title
    ws.merge_cells("A1:D1")
    ws.cell(row=1, column=1, value=f"{title} 情感极性统计").font = Font(name="微软雅黑", bold=True, size=13)
    for col, h in enumerate(["话题标签", "正面提及", "负面提及", "净情感(+为正)"], 1):
        c = ws.cell(row=3, column=col, value=h)
        c.font = header_font
        c.fill = header_fill
        c.alignment = wrap_align
        c.border = thin_border

    tag_pos = defaultdict(float)
    tag_neg = defaultdict(float)
    for item in data:
        tags = [t.strip() for t in item[4].split("/")]
        sentiment = item[3]
        for t in tags:
            if "+" in sentiment and "-" not in sentiment:
                tag_pos[t] += 1
            elif "-" in sentiment and "+" not in sentiment:
                tag_neg[t] += 1
            elif "+" in sentiment and "-" in sentiment:
                tag_pos[t] += 0.5
                tag_neg[t] += 0.5

    all_tags = sorted(set(list(tag_pos.keys()) + list(tag_neg.keys())))
    all_tags.sort(key=lambda t: (tag_neg.get(t,0) - tag_pos.get(t,0)), reverse=True)

    for i, tag in enumerate(all_tags, 4):
        pos = int(tag_pos.get(tag, 0))
        neg = int(tag_neg.get(tag, 0))
        net = pos - neg
        for col, val in enumerate([tag, pos, neg, net], 1):
            c = ws.cell(row=i, column=col, value=val)
            c.alignment = wrap_align
            c.border = thin_border
            c.font = Font(name="微软雅黑", size=10)
            if net <= -3:
                c.fill = red_fill
            elif net < 0:
                c.fill = neg_fill
            elif net > 0:
                c.fill = pos_fill
            else:
                c.fill = neu_fill

    ws.column_dimensions["A"].width = 22
    ws.column_dimensions["B"].width = 14
    ws.column_dimensions["C"].width = 14
    ws.column_dimensions["D"].width = 14

def write_profile_sheet(ws, title, profiles):
    ws.title = title
    ws.merge_cells("A1:E1")
    ws.cell(row=1, column=1, value=f"{title} 玩家画像").font = Font(name="微软雅黑", bold=True, size=13)
    for col, h in enumerate(["编号", "姓名", "年龄", "核心游戏经历", "玩家标签"], 1):
        c = ws.cell(row=3, column=col, value=h)
        c.font = header_font
        c.fill = header_fill
        c.alignment = wrap_align
        c.border = thin_border

    for i, (seq, name, age, games, label) in enumerate(profiles, 4):
        for col, val in enumerate([seq, name, age, games, label], 1):
            c = ws.cell(row=i, column=col, value=val)
            c.alignment = wrap_align
            c.border = thin_border
            c.font = Font(name="微软雅黑", size=10)

    for i, w in enumerate([6, 12, 6, 28, 48], 1):
        ws.column_dimensions[get_column_letter(i)].width = w

def build_workbook(group_name, data, profiles):
    wb = openpyxl.Workbook()
    ws = wb.active
    write_coding_sheet(ws, f"{group_name}-开放编码", data)
    ws2 = wb.create_sheet()
    write_stats_sheet(ws2, f"{group_name}-情感统计", data)
    ws3 = wb.create_sheet()
    write_profile_sheet(ws3, f"{group_name}-玩家画像", profiles)
    return wb

