def write_section_title(ws, row, title):
    ws.merge_cells(f"A{row}:F{row}")
    ws.cell(row=row, column=1, value=title).font = Font(name="微软雅黑", bold=True, size=13, color="2F5496")
    return row + 1

def write_sub_title(ws, row, title):
    ws.merge_cells(f"A{row}:F{row}")
    ws.cell(row=row, column=1, value=title).font = Font(name="微软雅黑", bold=True, size=11, color="4472C4")
    return row + 1

def write_body(ws, row, text):
    ws.merge_cells(f"A{row}:F{row}")
    c = ws.cell(row=row, column=1, value=text)
    c.font = body_font
    c.alignment = wrap_align
    return row + 1

def write_table_row(ws, row, cols, header=False):
    for i, val in enumerate(cols, 1):
        c = ws.cell(row=row, column=i, value=val)
        c.alignment = wrap_align
        c.border = thin_border
        if header:
            c.font = Font(name="微软雅黑", bold=True, size=10, color="FFFFFF")
            c.fill = header_fill
        else:
            c.font = body_font
    return row + 1

def write_table(ws, row, headers, data):
    row = write_table_row(ws, row, headers, header=True)
    for d in data:
        row = write_table_row(ws, row, d)
    return row + 1

